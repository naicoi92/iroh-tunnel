//! The BusyBox/SysV init script that `busybox.rs` installs: a pure renderer
//! (no I/O), so the script can be executed in tests on any Unix host.
//!
//! Every interpolated value is a POSIX shell literal (`policy::shell_quote`):
//! no path character is ever interpreted by the root shell running the script.

use super::super::pin::Pin;
use super::super::policy::shell_quote;
use super::super::types::ServiceInvocation;
use crate::error::CliError;
use anyhow::Result;
use std::path::{Path, PathBuf};

/// What the init script runs: one role's registration.
pub(super) struct InitScript<'a> {
    pub(super) role: &'a str,
    pub(super) invocation: ServiceInvocation,
    pub(super) binary: &'a Path,
    pub(super) config: &'a Path,
    pub(super) state: &'a Path,
    pub(super) pin: Option<&'a Pin>,
}

/// Where the script keeps its runtime files on the host.
pub(super) struct ScriptLayout {
    pidfile: PathBuf,
    logfile: PathBuf,
    proc_root: PathBuf,
}

impl ScriptLayout {
    /// The production layout of `role`'s script.
    pub(super) fn for_role(role: &str) -> Self {
        Self {
            pidfile: PathBuf::from(format!("/var/run/iroh-tunnel-{role}.pid")),
            logfile: PathBuf::from(format!("/var/log/iroh-tunnel-{role}.log")),
            proc_root: PathBuf::from("/proc"),
        }
    }
}

/// `path` as text, or a config error naming it: the script is text, and a
/// lossy conversion would silently register a different path.
fn utf8<'p>(what: &str, path: &'p Path) -> Result<&'p str> {
    path.to_str().ok_or_else(|| {
        CliError::Config(format!(
            "{what} path is not valid UTF-8: {}",
            path.display()
        ))
        .into()
    })
}

impl InitScript<'_> {
    /// Render the script body.
    ///
    /// # Errors
    ///
    /// [`crate::error::CliError::Config`] when a path is not valid UTF-8.
    pub(super) fn render(&self, layout: &ScriptLayout) -> Result<String> {
        let role = self.role;
        let role_arg = if self.invocation == ServiceInvocation::Combined {
            "\"$ROLE\" "
        } else {
            ""
        };
        let binary = shell_quote(utf8("binary", self.binary)?);
        let config = shell_quote(utf8("config", self.config)?);
        let state = shell_quote(utf8("state", self.state)?);
        let pidfile = shell_quote(utf8("PID file", &layout.pidfile)?);
        let logfile = shell_quote(utf8("log", &layout.logfile)?);
        let proc_root = shell_quote(utf8("proc", &layout.proc_root)?);
        let role_q = shell_quote(role);
        // A root service reads a user's files: say whose (SM-04).
        // A SID pin is rejected by `install` before this runs.
        let pin_lines = self.pin.map_or_else(String::new, |p| {
            let uid = p
                .unix_uid()
                .map(|u| format!("export {}={u}\n", super::super::trust::ENV_TRUSTED_UID));
            format!("# {}\n{}", p.record(), uid.unwrap_or_default())
        });
        Ok(format!(
            r#"#!/bin/sh
# Auto-generated by `iroh-tunnel service install` — do not edit by hand.
# BusyBox/SysV init script for iroh-tunnel ({role}).

DAEMON={binary}
ROLE={role_q}
CONFIG={config}
export IROH_TUNNEL_STATE_DIR={state}
{pin_lines}PIDFILE={pidfile}
LOG={logfile}
PROC={proc_root}

start() {{
    if [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE" 2>/dev/null)" 2>/dev/null; then
        echo "iroh-tunnel ($ROLE) already running (pid $(cat "$PIDFILE"))"
        return 0
    fi
    echo "Starting iroh-tunnel ($ROLE)"
    "$DAEMON" {role_arg}run --config "$CONFIG" >> "$LOG" 2>&1 &
    echo $! > "$PIDFILE"
}}

stop() {{
    if [ ! -f "$PIDFILE" ]; then return 0; fi
    PID="$(cat "$PIDFILE" 2>/dev/null)"
    if [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null; then
        echo "Stopping iroh-tunnel ($ROLE) (pid $PID)"
        kill -TERM "$PID" 2>/dev/null || true
        # Give iroh-tunnel up to 5s to drain on SIGTERM, then force-kill.
        i=0
        while [ "$i" -lt 5 ] && kill -0 "$PID" 2>/dev/null; do
            sleep 1; i=$((i + 1))
        done
        kill -0 "$PID" 2>/dev/null && kill -KILL "$PID" 2>/dev/null || true
    fi
    rm -f "$PIDFILE"
}}

status() {{
    if [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE" 2>/dev/null)" 2>/dev/null; then
        echo "iroh-tunnel ($ROLE) is running (pid $(cat "$PIDFILE"))"
        return 0
    fi
    echo "iroh-tunnel ($ROLE) is not running"
    return 3
}}

case "$1" in
    start) start ;;
    stop) stop ;;
    restart) stop; start ;;
    status) status ;;
    *) echo "Usage: $0 {{start|stop|restart|status}}"; exit 1 ;;
esac
exit $?
"#
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::super::super::effective_binary::{parse_busybox_script, EffectiveBinary};
    use super::*;
    use crate::error::CliError;

    fn render(role: &str, binary: &str, invocation: ServiceInvocation) -> String {
        InitScript {
            role,
            invocation,
            binary: Path::new(binary),
            config: Path::new("/c"),
            state: Path::new("/s"),
            pin: None,
        }
        .render(&ScriptLayout::for_role(role))
        .unwrap()
    }

    #[test]
    fn format_script_embeds_paths_and_all_verbs() {
        let s = InitScript {
            role: "serve",
            invocation: ServiceInvocation::Combined,
            binary: Path::new("/usr/local/bin/iroh-tunnel"),
            config: Path::new("/etc/iroh-tunnel/serve.toml"),
            state: Path::new("/var/lib/iroh-tunnel"),
            pin: None,
        }
        .render(&ScriptLayout::for_role("serve"))
        .unwrap();
        assert!(s.starts_with("#!/bin/sh"), "must start with sh shebang");
        assert!(s.contains("DAEMON=/usr/local/bin/iroh-tunnel\n"), "{s}");
        assert!(s.contains("ROLE=serve\n"), "{s}");
        assert!(s.contains("CONFIG=/etc/iroh-tunnel/serve.toml\n"), "{s}");
        assert!(
            s.contains("export IROH_TUNNEL_STATE_DIR=/var/lib/iroh-tunnel\n"),
            "{s}"
        );
        assert!(
            s.contains("PIDFILE=/var/run/iroh-tunnel-serve.pid\n"),
            "{s}"
        );
        assert!(s.contains("LOG=/var/log/iroh-tunnel-serve.log\n"), "{s}");
        assert!(s.contains("PROC=/proc\n"), "{s}");
        // The daemon invocation passes the role through the ROLE variable —
        // not a per-role literal.
        assert!(
            s.contains("\"$DAEMON\" \"$ROLE\" run --config \"$CONFIG\""),
            "daemon invocation wrong: {s}"
        );
        // All four init verbs must be wired in the case block.
        for arm in [
            "start) start",
            "stop) stop",
            "restart) stop; start",
            "status) status",
        ] {
            assert!(s.contains(arm), "missing case arm `{arm}`:\n{s}");
        }
    }

    #[test]
    fn invocation_form_survives_managed_paths_with_spaces() {
        for role in ["serve", "access"] {
            for (invocation, expected) in [
                (ServiceInvocation::Combined, "\"$ROLE\" run"),
                (ServiceInvocation::Standalone, "run"),
            ] {
                let body = render(role, "/managed path/copy", invocation);
                assert!(body.contains("DAEMON='/managed path/copy'\n"), "{body}");
                assert!(
                    body.contains(&format!("\"$DAEMON\" {expected} --config \"$CONFIG\"")),
                    "{body}"
                );
            }
        }
    }

    #[test]
    fn managed_path_renders_as_one_argument_in_each_backend() {
        let copy = "/Library/Application Support/iroh-tunnel/bin/serve/iroh-tunnel";
        let script = render("serve", copy, ServiceInvocation::Combined);
        // Assigned as one single-quoted literal and expanded quoted: one word.
        assert!(script.contains(&format!("DAEMON='{copy}'\n")), "{script}");
        assert!(
            script.contains("\"$DAEMON\" \"$ROLE\" run --config \"$CONFIG\""),
            "{script}"
        );
        assert_eq!(
            parse_busybox_script(Some(&script)),
            EffectiveBinary::Binary(PathBuf::from(copy))
        );
    }

    #[test]
    fn effective_binary_round_trips_the_generated_script() {
        for binary in ["/a b/iroh-tunnel", "/it's $HOME/iroh-tunnel"] {
            let script = render("serve", binary, ServiceInvocation::Combined);
            assert_eq!(
                parse_busybox_script(Some(&script)),
                EffectiveBinary::Binary(PathBuf::from(binary)),
                "{script}"
            );
        }
    }

    #[test]
    fn non_utf8_config_is_refused() {
        use std::os::unix::ffi::OsStrExt;
        let config = Path::new(std::ffi::OsStr::from_bytes(b"/c\xff"));
        let err = InitScript {
            role: "serve",
            invocation: ServiceInvocation::Combined,
            binary: Path::new("/b"),
            config,
            state: Path::new("/s"),
            pin: None,
        }
        .render(&ScriptLayout::for_role("serve"))
        .unwrap_err();
        match err.downcast_ref::<CliError>() {
            Some(CliError::Config(msg)) => {
                assert!(msg.contains("not valid UTF-8"), "{msg}");
                assert!(msg.contains(&config.display().to_string()), "{msg}");
            }
            other => panic!("expected a config error, got {other:?}: {err:#}"),
        }
    }

    /// Execute the rendered script against a temporary layout and fake daemon.
    mod exec {
        use super::super::super::super::policy::shell_quote;
        use super::*;
        use std::cell::RefCell;
        use std::os::unix::fs::PermissionsExt;
        use std::process::{Command, Output, Stdio};
        use std::time::{Duration, Instant};

        /// How the fake daemon treats SIGTERM.
        pub(super) enum DaemonKind {
            /// Default disposition: SIGTERM ends it.
            Exits,
            /// `trap '' TERM`: only SIGKILL ends it.
            IgnoresTerm,
        }

        pub(super) struct ScriptHarness {
            pub(super) dir: tempfile::TempDir,
            pub(super) script: PathBuf,
            pub(super) layout: ScriptLayout,
            pub(super) record: PathBuf,
            seen: RefCell<Vec<u32>>,
        }

        fn write_executable(path: &Path, body: &str) {
            std::fs::write(path, body).unwrap();
            std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
        }

        /// Whether `pid` is a live process (`kill -0`).
        pub(super) fn alive(pid: u32) -> bool {
            Command::new("kill")
                .arg("-0")
                .arg(pid.to_string())
                .stderr(Stdio::null())
                .status()
                .unwrap()
                .success()
        }

        /// Poll until `pid` is gone; `false` if it outlived `timeout`.
        pub(super) fn wait_gone(pid: u32, timeout: Duration) -> bool {
            let deadline = Instant::now() + timeout;
            while alive(pid) {
                if Instant::now() > deadline {
                    return false;
                }
                std::thread::sleep(Duration::from_millis(50));
            }
            true
        }

        impl ScriptHarness {
            pub(super) fn new(
                binary_name: &str,
                config_name: &str,
                state_name: &str,
                invocation: ServiceInvocation,
                daemon: DaemonKind,
            ) -> Self {
                let dir = tempfile::tempdir().unwrap();
                let root = dir.path();
                let record = root.join("record");
                let binary = root.join(binary_name);
                let trap = match daemon {
                    DaemonKind::Exits => "",
                    DaemonKind::IgnoresTerm => "trap '' TERM\n",
                };
                let record_q = shell_quote(record.to_str().unwrap());
                write_executable(
                    &binary,
                    &format!(
                        "#!/bin/sh\n{trap}{{ for a in \"$@\"; do printf '%s\\n' \"$a\"; done; \
                         printf 'STATE=%s\\n' \"$IROH_TUNNEL_STATE_DIR\"; }} > {record_q}\n\
                         exec sleep 30\n"
                    ),
                );
                let config = root.join(config_name);
                let state = root.join(state_name);
                let layout = ScriptLayout {
                    pidfile: root.join("run.pid"),
                    logfile: root.join("run.log"),
                    proc_root: root.join("proc"),
                };
                std::fs::create_dir(&layout.proc_root).unwrap();
                let body = InitScript {
                    role: "serve",
                    invocation,
                    binary: &binary,
                    config: &config,
                    state: &state,
                    pin: None,
                }
                .render(&layout)
                .unwrap();
                let script = root.join("init.sh");
                write_executable(&script, &body);
                Self {
                    dir,
                    script,
                    layout,
                    record,
                    seen: RefCell::new(Vec::new()),
                }
            }

            /// Run the script with `verb`; remembers the PID it leaves behind.
            pub(super) fn run(&self, verb: &str) -> Output {
                let output = Command::new("/bin/sh")
                    .arg(&self.script)
                    .arg(verb)
                    .current_dir(self.dir.path())
                    .stdin(Stdio::null())
                    .output()
                    .unwrap();
                if let Some(pid) = self.read_pid() {
                    self.seen.borrow_mut().push(pid);
                }
                output
            }

            fn read_pid(&self) -> Option<u32> {
                let text = std::fs::read_to_string(&self.layout.pidfile).ok()?;
                text.lines().next()?.trim().parse().ok()
            }

            /// The PID on the PID file's first line.
            pub(super) fn pidfile_pid(&self) -> u32 {
                self.read_pid().expect("PID file holds a PID")
            }

            /// The daemon's record (argv lines, then `STATE=`), once complete.
            pub(super) fn wait_record(&self) -> String {
                let deadline = Instant::now() + Duration::from_secs(5);
                loop {
                    if let Ok(text) = std::fs::read_to_string(&self.record) {
                        if text.lines().any(|l| l.starts_with("STATE=")) {
                            return text;
                        }
                    }
                    assert!(Instant::now() < deadline, "daemon never wrote its record");
                    std::thread::sleep(Duration::from_millis(20));
                }
            }

            /// Fake `/proc/<pid>` entry: `exe` link and NUL-separated `cmdline`.
            pub(super) fn fake_proc(&self, pid: u32, exe: &str, cmdline: &[&str]) {
                let entry = self.layout.proc_root.join(pid.to_string());
                std::fs::create_dir_all(&entry).unwrap();
                self.set_exe(pid, exe);
                let mut bytes = Vec::new();
                for arg in cmdline {
                    bytes.extend_from_slice(arg.as_bytes());
                    bytes.push(0);
                }
                std::fs::write(entry.join("cmdline"), bytes).unwrap();
            }

            /// Re-point `/proc/<pid>/exe` atomically (temp link + rename).
            pub(super) fn set_exe(&self, pid: u32, target: &str) {
                let entry = self.layout.proc_root.join(pid.to_string());
                let tmp = entry.join("exe.tmp");
                let _ = std::fs::remove_file(&tmp);
                std::os::unix::fs::symlink(target, &tmp).unwrap();
                std::fs::rename(&tmp, entry.join("exe")).unwrap();
            }

            /// An orphan `sleep 30` (reaped by init, never a zombie child).
            pub(super) fn spawn_unrelated(&self) -> u32 {
                let out = Command::new("sh")
                    .arg("-c")
                    .arg("sleep 30 >/dev/null 2>&1 & echo $!")
                    .stdin(Stdio::null())
                    .output()
                    .unwrap();
                let pid = String::from_utf8(out.stdout)
                    .unwrap()
                    .trim()
                    .parse()
                    .unwrap();
                self.seen.borrow_mut().push(pid);
                pid
            }
        }

        impl Drop for ScriptHarness {
            fn drop(&mut self) {
                for pid in self.seen.borrow().iter() {
                    let _ = Command::new("kill")
                        .arg("-9")
                        .arg(pid.to_string())
                        .stderr(Stdio::null())
                        .status();
                }
            }
        }

        #[test]
        fn metachar_config_path_reaches_daemon_literally() {
            let config = r#"c $(touch pwned) `touch pwned2` "q" 'a' \b.toml"#;
            let h = ScriptHarness::new(
                "iroh-tunnel",
                config,
                "state",
                ServiceInvocation::Combined,
                DaemonKind::Exits,
            );
            h.run("start");
            let record = h.wait_record();
            let full = h.dir.path().join(config);
            let expected = format!("--config\n{}\n", full.to_str().unwrap());
            assert!(record.contains(&expected), "{record}");
            assert!(!h.dir.path().join("pwned").exists(), "$() ran");
            assert!(!h.dir.path().join("pwned2").exists(), "backticks ran");
        }

        #[test]
        fn metachar_binary_and_state_paths_are_literal() {
            let h = ScriptHarness::new(
                "it $HOME `x`-tunnel",
                "c.toml",
                "s $HOME `x`",
                ServiceInvocation::Standalone,
                DaemonKind::Exits,
            );
            h.run("start");
            let record = h.wait_record();
            let state = h.dir.path().join("s $HOME `x`");
            let expected = format!("STATE={}", state.to_str().unwrap());
            assert!(record.lines().any(|l| l == expected), "{record}");
            assert!(alive(h.pidfile_pid()));
        }

        /// The harness itself: a TERM-ignoring daemon survives SIGTERM, fake
        /// proc entries read back, and an unrelated process is independent.
        #[test]
        fn harness_controls_daemon_and_fake_proc() {
            let h = ScriptHarness::new(
                "iroh-tunnel",
                "c.toml",
                "state",
                ServiceInvocation::Combined,
                DaemonKind::IgnoresTerm,
            );
            h.run("start");
            h.wait_record();
            let pid = h.pidfile_pid();
            Command::new("kill")
                .arg("-TERM")
                .arg(pid.to_string())
                .status()
                .unwrap();
            assert!(!wait_gone(pid, Duration::from_millis(300)), "TERM ignored");

            let other = h.spawn_unrelated();
            assert!(alive(other));
            h.fake_proc(other, "/bin/sleep", &["sleep", "30"]);
            h.set_exe(other, "/elsewhere");
            let entry = h.layout.proc_root.join(other.to_string());
            assert_eq!(
                std::fs::read_link(entry.join("exe")).unwrap(),
                PathBuf::from("/elsewhere")
            );
            assert_eq!(
                std::fs::read(entry.join("cmdline")).unwrap(),
                b"sleep\x0030\x00"
            );
            Command::new("kill")
                .arg("-9")
                .arg(other.to_string())
                .status()
                .unwrap();
            assert!(wait_gone(other, Duration::from_secs(5)));
        }
    }
}
