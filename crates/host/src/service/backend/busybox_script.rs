//! The BusyBox/SysV init script that `busybox.rs` installs: a pure renderer
//! (no I/O), so the script can be executed in tests on any Unix host.
//!
//! Every interpolated value is a POSIX shell literal (`policy::shell_quote`):
//! no path character is ever interpreted by the root shell running the script.

use super::super::policy::shell_quote;
use super::super::registration::RegistrationInput;
use crate::error::CliError;
use anyhow::Result;
use std::path::{Path, PathBuf};

/// Where the script keeps its runtime files on the host.
pub(super) struct ScriptLayout {
    pidfile: PathBuf,
    logfile: PathBuf,
    proc_root: PathBuf,
}

impl ScriptLayout {
    /// The production layout of `role`'s script.
    pub(super) fn for_role(role: &str) -> Self {
        Self {
            pidfile: PathBuf::from(format!("/var/run/iroh-tunnel-{role}.pid")),
            logfile: PathBuf::from(format!("/var/log/iroh-tunnel-{role}.log")),
            proc_root: PathBuf::from("/proc"),
        }
    }
}

/// `path` as text, or a config error naming it: the script is text, and a
/// lossy conversion would silently register a different path.
fn utf8<'p>(what: &str, path: &'p Path) -> Result<&'p str> {
    path.to_str().ok_or_else(|| {
        CliError::Config(format!(
            "{what} path is not valid UTF-8: {}",
            path.display()
        ))
        .into()
    })
}

/// Render the init script of `reg` with its runtime files at `layout`.
///
/// `reg.role` must be a plain identifier (a `Role::name()`): it appears
/// unquoted in the header comment and runtime file names.
///
/// # Errors
///
/// [`crate::error::CliError::Config`] when a path is not valid UTF-8.
pub(super) fn render_script(reg: &RegistrationInput<'_>, layout: &ScriptLayout) -> Result<String> {
    // Header comment only; the script reads the role from `ROLE`.
    let role = reg.role;
    let role_arg = if reg.role_arg().is_some() {
        "\"$ROLE\" "
    } else {
        ""
    };
    let binary = shell_quote(utf8("binary", reg.binary)?);
    let config = shell_quote(utf8("config", reg.config)?);
    let state = shell_quote(utf8("state", reg.state)?);
    let pidfile = shell_quote(utf8("PID file", &layout.pidfile)?);
    let logfile = shell_quote(utf8("log", &layout.logfile)?);
    let proc_root = shell_quote(utf8("proc", &layout.proc_root)?);
    let role_q = shell_quote(role);
    // A root service reads a user's files: say whose (SM-04).
    // A SID pin is rejected by `install` before this runs.
    let pin_lines = reg.pin.map_or_else(String::new, |p| {
        let uid = p
            .unix_uid()
            .map(|u| format!("export {}={u}\n", super::super::trust::ENV_TRUSTED_UID));
        format!("# {}\n{}", p.record(), uid.unwrap_or_default())
    });
    Ok(format!(
        r#"#!/bin/sh
# Auto-generated by `iroh-tunnel service install` — do not edit by hand.
# BusyBox/SysV init script for iroh-tunnel ({role}).

DAEMON={binary}
ROLE={role_q}
CONFIG={config}
export IROH_TUNNEL_STATE_DIR={state}
{pin_lines}PIDFILE={pidfile}
LOG={logfile}
PROC={proc_root}

# The PID file: the daemon's PID, then the launched DAEMON path and a `.`
# sentinel (so trailing characters of the path survive `$(...)`). A file
# with no second line was written by an earlier script (legacy).
SEP=$(printf '\001')

read_pidfile() {{
    PID=$(head -n 1 "$PIDFILE" 2>/dev/null)
    REC=$(tail -n +2 "$PIDFILE" 2>/dev/null)
    REC=${{REC%.}}
}}

# $1 the process's exe, $2 the expected path: equal, or replaced on disk.
exe_matches() {{
    [ -n "$2" ] && {{ [ "$1" = "$2" ] || [ "$1" = "$2 (deleted)" ]; }}
}}

# A legacy PID file: 0 = the current DAEMON, or an iroh-tunnel executable
# running this role with this config; 1 = another process; 2 = unreadable.
legacy_match() {{
    exe_matches "$1" "$DAEMON" && return 0
    NAME=${{1%" (deleted)"}}; NAME=${{NAME##*/}}
    case "$NAME" in iroh-tunnel*) ;; *) return 1 ;; esac
    CMD=$(tr '\000' '\001' 2>/dev/null < "$PROC/$PID/cmdline") || return 2
    TAIL="${{SEP}}run${{SEP}}--config$SEP$CONFIG$SEP"
    case "$CMD" in
        *"$SEP$ROLE$TAIL") return 0 ;;
        *"$TAIL") [ "$NAME" = "iroh-tunnel-$ROLE" ] && return 0 ;;
    esac
    return 1
}}

# Whether the PID file names the daemon: 0 = ours, 1 = stale (no file, no
# such process, a zombie, or another executable), 2 = unverifiable (an
# unreadable PID file, or a live process whose executable cannot be read).
identity() {{
    [ -f "$PIDFILE" ] || return 1
    [ -r "$PIDFILE" ] || return 2
    read_pidfile
    case "$PID" in ''|0*|*[!0-9]*) return 1 ;; esac
    if ! kill -0 "$PID" 2>/dev/null; then
        # Alive but not ours to signal (EPERM), or dead.
        [ -e "$PROC/$PID" ] && return 2
        return 1
    fi
    [ -e "$PROC/$PID" ] || return 2
    # A zombie (state `Z` after the last ") " of its stat) holds nothing.
    ST=$(cat "$PROC/$PID/stat" 2>/dev/null) && case ${{ST##*") "}} in Z*) return 1 ;; esac
    EXE=$(readlink "$PROC/$PID/exe" 2>/dev/null) || return 2
    if [ -n "$REC" ]; then
        exe_matches "$EXE" "$REC"
        return
    fi
    legacy_match "$EXE"
}}

unverifiable() {{
    echo "iroh-tunnel ($ROLE): cannot verify that pid $PID is the daemon; $PIDFILE kept" >&2
}}

start() {{
    identity
    case $? in
        0) echo "iroh-tunnel ($ROLE) already running (pid $PID)"; return 0 ;;
        2) unverifiable; return 1 ;;
    esac
    rm -f "$PIDFILE"
    echo "Starting iroh-tunnel ($ROLE)"
    "$DAEMON" {role_arg}run --config "$CONFIG" >> "$LOG" 2>&1 &
    printf '%s\n%s.' "$!" "$DAEMON" > "$PIDFILE"
}}

stop() {{
    identity
    case $? in
        2) unverifiable; return 1 ;;
        0)
            echo "Stopping iroh-tunnel ($ROLE) (pid $PID)"
            kill -TERM "$PID" 2>/dev/null
            # Give iroh-tunnel up to 5s to drain on SIGTERM, then force-kill
            # only if the PID still runs the daemon.
            i=0
            while [ "$i" -lt 5 ] && identity; do
                sleep 1; i=$((i + 1))
            done
            if identity; then kill -KILL "$PID" 2>/dev/null; fi
            ;;
    esac
    rm -f "$PIDFILE"
}}

status() {{
    identity
    case $? in
        0) echo "iroh-tunnel ($ROLE) is running (pid $PID)"; return 0 ;;
        2) echo "iroh-tunnel ($ROLE) status unknown: cannot verify pid $PID"; return 4 ;;
    esac
    echo "iroh-tunnel ($ROLE) is not running"
    return 3
}}

case "$1" in
    start) start ;;
    stop) stop ;;
    restart) stop && start ;;
    status) status ;;
    *) echo "Usage: $0 {{start|stop|restart|status}}"; exit 1 ;;
esac
exit $?
"#
    ))
}

